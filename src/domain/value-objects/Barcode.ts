import { DomainError } from '../errors/DomainError';

/**
 * A scanned or typed barcode. Normalised so that a code typed by hand and the same code read
 * by the camera compare as equal.
 */
export class Barcode {
  private constructor(readonly value: string) {}

  static create(raw: string): Barcode {
    const normalised = raw.trim().replace(/\s+/g, '');
    if (normalised.length === 0) {
      throw new DomainError('Barcode cannot be empty');
    }
    if (normalised.length > 64) {
      throw new DomainError('Barcode is too long to be genuine');
    }
    return new Barcode(normalised);
  }

  /** Returns null instead of throwing, for optional input such as a loose-goods product. */
  static tryCreate(raw: string | null | undefined): Barcode | null {
    if (raw === null || raw === undefined || raw.trim() === '') return null;
    try {
      return Barcode.create(raw);
    } catch {
      return null;
    }
  }

  /**
   * The check digit that completes an EAN-13, given its first twelve digits.
   *
   * Alternating weights of one and three from the left, then whatever is needed to round the
   * sum up to a multiple of ten. This is what lets a scanner reject a smudged read instead
   * of reporting a different article.
   */
  static ean13CheckDigit(first12: string): string {
    if (!/^\d{12}$/.test(first12)) {
      throw new DomainError('A check digit needs the first twelve digits');
    }
    let sum = 0;
    for (let i = 0; i < 12; i += 1) {
      sum += Number(first12[i]) * (i % 2 === 0 ? 1 : 3);
    }
    return String((10 - (sum % 10)) % 10);
  }

  /** Whether a code is thirteen digits whose last one agrees with the other twelve. */
  static isValidEan13(value: string): boolean {
    const digits = value.trim();
    if (!/^\d{13}$/.test(digits)) return false;
    return Barcode.ean13CheckDigit(digits.slice(0, 12)) === digits[12];
  }

  /**
   * A barcode for an article that arrived without one.
   *
   * Begins 20, the prefix GS1 reserves for a shop's own use, so a generated code can never
   * collide with a real manufacturer's and can never be mistaken for one. The ten digits
   * after it are random rather than sequential: a counter would need a shared source of
   * truth, and the database already refuses a duplicate, so the caller retries on the
   * vanishingly rare clash instead.
   */
  static generateInStore(): Barcode {
    let body = '20';
    for (let i = 0; i < 10; i += 1) {
      body += String(Math.floor(Math.random() * 10));
    }
    return new Barcode(body + Barcode.ean13CheckDigit(body));
  }

  /** True when this code was generated by the shop rather than printed by a supplier. */
  get isInStore(): boolean {
    return this.value.length === 13 && this.value.startsWith('20');
  }

  equals(other: Barcode): boolean {
    return this.value === other.value;
  }

  toString(): string {
    return this.value;
  }
}
